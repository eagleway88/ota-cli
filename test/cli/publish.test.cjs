const { test } = require('node:test')
const assert = require('node:assert/strict')
const { writeFile, access } = require('node:fs/promises')
const path = require('node:path')
const { fixture } = require('../fixtures/api.cjs')
const { cli } = require('../fixtures/cli.cjs')
const release = { targetVersionCode: 110, baseVersionCodes: [100], platforms: ['windows', 'macos', 'linux'], updateType: 'hot', releaseScope: 'public', userIds: [], mandatory: false }
async function config(f, targets = { desktop: { file: f.zip, ...release } }) {
  await writeFile(path.join(f.directory, 'ota-cli.config.ts'), 'export default ' + JSON.stringify({ baseURL: f.baseURL, appName: 'desktop', targets }))
}
test('CLI package version comes from the manifest', async t => {
  const f = await fixture(t)
  const output = await cli(f, ['--version'])
  assert.equal(output.code, 0)
  assert.equal(output.stdout.trim(), require('../../package.json').version)
})
test('real CLI deploy publishes one desktop ZIP for three platforms and keeps hook logs off stdout', async t => {
  const f = await fixture(t)
  await writeFile(path.join(f.directory, 'ota-cli.config.ts'), 'export default { ...' + JSON.stringify({ baseURL: f.baseURL, appName: 'desktop', targets: { desktop: { file: f.zip, ...release } } }) + ', onPublished() { console.log("hook diagnostic") } }')
  const output = await cli(f, ['release', 'deploy', '--target', 'desktop', '--json'])
  assert.equal(output.code, 0, output.stderr)
  assert.equal(JSON.parse(output.stdout).deployments[0].result.status, 'published')
  assert.match(output.stderr, /hook diagnostic/)
  assert.equal(f.calls.filter(call => call.path.endsWith('/artifacts')).length, 1)
  assert.equal(f.drafts.size, 1)
  assert.deepEqual([...f.drafts.values()][0].platforms, ['windows', 'macos', 'linux'])
  assert.ok(!output.stdout.includes(f.accessKey)); assert.ok(!output.stderr.includes(f.accessKey))
})
test('real CLI policies share an artifact and dry-run never writes remotely or requires a key', async t => {
  const f = await fixture(t)
  await config(f, { stable: { file: f.zip, ...release }, beta: { file: f.zip, ...release, distributionChannel: 'beta' } })
  const dryRun = await cli(f, ['release', 'deploy', '--target', 'stable,beta', '--dry-run'], { OTA_ACCESS_KEY: '' })
  assert.equal(dryRun.code, 0, dryRun.stderr)
  assert.equal(JSON.parse(dryRun.stdout).dryRun, true); assert.equal(f.calls.length, 0)
  await assert.rejects(access(path.join(f.directory, '.ota-cli')))
  const output = await cli(f, ['release', 'deploy', '--target', 'stable,beta'])
  assert.equal(output.code, 0, output.stderr)
  assert.equal(JSON.parse(output.stdout).deployments.length, 2)
  assert.equal(f.calls.filter(call => call.path.endsWith('/artifacts')).length, 1)
  assert.equal(f.publications.size, 2)
})
test('resource upload and draft creation never publish implicitly', async t => {
  const f = await fixture(t)
  const base = ['--no-config', '--base-url', f.baseURL, '--app', 'desktop']
  const uploaded = await cli(f, [...base, 'artifact', 'upload', '--file', f.zip])
  assert.equal(uploaded.code, 0, uploaded.stderr)
  assert.equal(f.drafts.size, 0); assert.equal(f.publications.size, 0)
  const input = path.join(f.directory, 'release.json')
  await writeFile(input, JSON.stringify({ ...release, artifactId: JSON.parse(uploaded.stdout).artifactId }))
  const created = await cli(f, [...base, 'release', 'create', '--input', input, '--idempotency-key', 'cli-stable-key'])
  assert.equal(created.code, 0, created.stderr)
  assert.equal(JSON.parse(created.stdout).draft.status, 'draft')
  assert.equal(f.drafts.size, 1); assert.equal(f.publications.size, 0)
})
test('CLI makes one request on 401/403, gives distinct hints and never prints credentials', async t => {
  for (const status of [401, 403]) {
    const f = await fixture(t, { handle: async (call, send) => { send('denied ' + call.headers.authorization, status); return true } })
    const output = await cli(f, ['--no-config', '--base-url', f.baseURL, '--app', 'desktop', 'release', 'list'])
    assert.equal(output.code, 1)
    const error = JSON.parse(output.stderr)
    assert.equal(error.status, status)
    assert.match(error.hint, status === 401 ? /invalid/ : /lacks/)
    assert.equal(f.calls.length, 1)
    assert.ok(!output.stderr.includes(f.accessKey)); assert.ok(!output.stderr.includes('s'.repeat(43)))
  }
})
